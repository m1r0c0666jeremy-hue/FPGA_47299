# Row 1 positions deliberately leave room for the three-character binary mode.
row1={0:'模',1:'式',2:'：',7:'坐',8:'标',9:'：',10:'(',15:',',20:')',22:'倍',23:'率',24:'：',26:'倍'}
row2={i:c for i,c in enumerate('KEY3方向：')};row2.update({9:'状',10:'态',11:'：'})
template=template.replace('@ROW1@','\n'.join(f'                {i}:glyph={gid(c)};' for i,c in row1.items()))
template=template.replace('@ROW2@','\n'.join(f'                {i}:glyph={gid(c)};' for i,c in row2.items()))
template=template.replace('@BRAND@',cases('安路科技')).replace('@SPACE@',str(gid(' '))).replace('@ZERO@',str(gid('0')))
for c in chars:template=template.replace('@'+c+'@',str(gid(c)))
assert '@' not in template.replace('always @','always ')
(out/'scaling_osd.v').write_text(template,encoding='utf-8')
manifest={'font':Path(a.font).name,'font_sha256':hashlib.sha256(Path(a.font).read_bytes()).hexdigest(),
 'contest_glyphs_reused':''.join(c for c in chars if c in vendor_glyphs),
 'characters':chars,'glyph_size':[24,24],'logo_size':[96,62],
 'files':{f.name:hashlib.sha256(f.read_bytes()).hexdigest() for f in [out/'scaling_glyph_rom.v',out/'scaling_logo_rom.v',out/'scaling_osd.v',png]}}
(assets/'scaling_rom_manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(f'Generated {len(chars)} glyphs and {len(pixels)} logo pixels')
