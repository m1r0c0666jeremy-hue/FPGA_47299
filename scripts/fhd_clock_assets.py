"""Generate PH1P35 clocks using the installed vendor's PLL calculator.

The generated parameters and calculator stdout are retained for audit. Never
substitute requested frequencies for the calculator's actual divider result.
"""
from pathlib import Path
import hashlib,json,re,subprocess

R=Path(__file__).resolve().parents[1]
TD=Path('E:/TD 6.2.1')
DEP=TD/'ip/depot/PLLF6F1D0P0_1.0/Dependency.tcl'

def generate():
    out=R/'reports/clocks';out.mkdir(parents=True,exist_ok=True)
    script=R/'scripts/fhd_pll_vendor.tcl'
    result=subprocess.run([str(TD/'bin/td_commands_prompt.exe'),script.as_posix()],cwd=R,capture_output=True,text=True,check=True)
    (out/'vendor_calculator.log').write_text(result.stdout,encoding='utf-8')
    configs={}
    for name in ('system','hdmi'):
        divs=list(map(float,re.search(rf'{name} dividers=([^\r\n]+)',result.stdout)[1].split()))
        frac=list(map(float,re.search(rf'{name} fraction=([^\r\n]+)',result.stdout)[1].split()))
        bandwidth=list(map(int,re.search(rf'{name} bandwidth=([^\r\n]+)',result.stdout)[1].split()))
        count=3 if name=='system' else 2
        expected=[100,24,60] if name=='system' else [74.25,371.25]
        actual=[frac[0]/divs[i] for i in range(count)]
        assert all(abs(a/b-1)<1e-7 for a,b in zip(actual,expected)),(name,actual)
        fin=50 if name=='system' else 60
        configs[name]=dict(reference_MHz=fin,dividers=divs,fraction=frac,bandwidth=bandwidth,actual_MHz=actual)
        ports=['input wire refclk,reset','output wire lock']+[f'output wire clk{i}_out' for i in range(count)]
        lines=['// Generated by fhd_clock_assets.py using TD PLL Dependency.tcl.','// NOCOMP VCO feedback; all output dividers share this PLL VCO.',f'module fhd_{name}_pll('+', '.join(ports)+');']
        for i in range(count):
            lines += [f'wire clk{i}_buf;',f'PH1P_LOGIC_BUFG b{i}(.i(clk{i}_buf),.o(clk{i}_out));']
        params=['.FBKCLK("VCO_PHASE0")','.FBKCLK_INT("VCO_PHASE0")',f'.FIN("{fin:.9f}")',f'.REFCLK_DIV({int(divs[10])})',f'.FBCLK_DIV({int(frac[3])})']
        for i in range(count):
            d=int(divs[i]);params += [f'.CLKC{i}_ENABLE("ENABLE")',f'.CLKC{i}_DIV({d})',f'.CLKC{i}_CPHASE({d-1})',f'.CLKC{i}_DUTY_INT({(d+1)//2})']
        params += ['.PLL_USR_RST("ENABLE")','.PLL_FEED_TYPE("EXTERNAL")','.FEEDBK_MODE("NOCOMP")','.PLL_FASTLOOP("ENABLE")',f'.LPF_CAP({bandwidth[0]})',f'.ICP_CUR({bandwidth[1]})',f'.LPF_RES({bandwidth[2]})',f'.FRAC_ENABLE("{"ENABLE" if int(frac[2]) else "DISABLE"}")',f'.SDM_FRAC({int(frac[2])})']
        lines += ['ph1p_phy_pll_wrapper_25a56e5ce2f9 #('+',\n'.join(params)+') u_core (']
        connections=['.refclk(refclk)','.reset(reset)','.lock(lock)',".fbclk(1'b0)",".refclk_rst(1'b0)",".wakeup(1'b1)",".pllpd(1'b0)",".clkc_rst(2'b00)",".drp_clk(1'b0)",".drp_rstn(1'b1)",".drp_sel(1'b0)",".drp_rd(1'b0)",".drp_wr(1'b0)",".drp_addr(8'd0)",".drp_wdata(8'd0)",".psclk(1'b0)",".psclksel(3'd0)",".psstep(1'b0)",".psdown(1'b0)",".cps_step(1'b0)",".ssc_reset(1'b0)"]
        for i in range(7):connections += [f".clk{i}_en(1'b{int(i<count)})",f'.clk{i}_out({f"clk{i}_buf" if i<count else ""})',f'.clkb{i}_out()']
        lines += [',\n'.join(connections),');','endmodule','']
        (R/f'rtl/color_regions/fhd_{name}_pll.v').write_text('\n'.join(lines),encoding='utf-8')
    configs['calculator']=dict(path=str(DEP),sha256=hashlib.sha256(DEP.read_bytes()).hexdigest())
    (out/'pll_parameters.json').write_text(json.dumps(configs,indent=2),encoding='utf-8')
    print(json.dumps(configs,indent=2))

if __name__=='__main__':generate()
