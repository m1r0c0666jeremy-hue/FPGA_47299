"""Audit first, then create a unique formal bit/source/report delivery."""
from pathlib import Path
import argparse,datetime,hashlib,json,re,shutil,zipfile
from audit_stable_regions import audit
R=Path(__file__).resolve().parents[1]
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def write_new(p,obj):
    with p.open('x',encoding='utf-8') as f:json.dump(obj,f,ensure_ascii=False,indent=2)
p=argparse.ArgumentParser();p.add_argument('--attempt',required=True);a=p.parse_args()
attempt=(R/a.attempt).resolve();obj=audit(attempt,True)
for n in ('stable_regions_delivery.json','stable_regions_build_manifest.json','stable_regions_software_inputs.json'):
    assert not (R/'reports'/n).exists(),f'Existing release record is protected: {n}'
stamp=datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=8))).strftime('%Y%m%d_%H%M%S')
dest=R/'build'/f'target_color_regions_stable_{stamp}';dest.mkdir(exist_ok=False)
bit=dest/'target_color_regions.bit';shutil.copy2(attempt/'target_color_regions.bit',bit)
assert sha(bit)==obj['bit_sha256']
report_names=['target_color_regions_phy.ts','target_color_regions_phy.area','target_color_regions_pr.timing',
              'target_color_regions_exception.timing','target_color_regions_clocks.txt','inputs.json','inputs_after.json']
for n in report_names:shutil.copy2(attempt/n,dest/n)
shutil.copy2(R/'reports'/(attempt.name+'.log'),dest/'td_build.log')
shutil.copy2(attempt/'source_snapshot.zip',dest/'compiled_source_snapshot.zip')
obj['production_directory']=dest.relative_to(R).as_posix()
write_new(R/'reports/stable_regions_build_manifest.json',obj)
software_files={p for p in (R/'scripts').glob('test_stable_*.py')}|{R/'sim/tb_stable_live.sv',R/'sim/tb_stable_faults.sv'}
software_files|={p for p in (R/'build/sim').glob('stable_*/*.sv')}
software_files|={p for p in (R/'rtl/color_regions').glob('stable_*.v')}
software_inputs={p.relative_to(R).as_posix():sha(p) for p in sorted(software_files)}
write_new(R/'reports/stable_regions_software_inputs.json',dict(inputs=software_inputs,evidence=obj['evidence'],
    note='Final executed test sources/generated benches and final production RTL. Classifier/colour-mask/filter vectors are regenerated by the recorded scripts. Hardware remains unmeasured.'))
report=R/'reports/双色工具正式功能版验证报告.md';text=report.read_text(encoding='utf-8')
block=f'''最终 TD 完整综合、布局布线通过，编译前后 **{obj['input_count']} 项输入哈希一致**。

| 项目 | 最终结果 |
|---|---|
| Slice / LUT6 / 寄存器 | {obj['resources']['Slice']}/21216 / {obj['resources']['LUT6']}/21216 / {obj['resources']['Register']}/42432 |
| ERAM20K / DSP | {obj['resources']['ERAM20K']}/108 / {obj['resources']['DSP']}/40 |
| 建立 / 保持最差余量 | +{obj['timing_ns']['SWNS']:.3f} ns / +{obj['timing_ns']['HWNS']:.3f} ns |
| STA 覆盖率 | {obj['sta_coverage_percent']:.2f}% |
| 被忽略的最大延迟例外 | {obj['ignored_max_delay_constraints']} 条，保留原始说明 |
| 实物 | 待验 |

正式 bit：`{bit.relative_to(R).as_posix()}`。

SHA256：`{obj['bit_sha256']}`。

最终编译目录：`{attempt.relative_to(R).as_posix()}`；完整原始报告在该目录及正式目录保留。`compiled_source_snapshot.zip` 是直接冻结的编译输入包；`color_regions_stable_source.zip` 另包含生成器、检查脚本、仿真源码、证据日志和操作文档。详细逐文件哈希见 `stable_regions_delivery.json`、`stable_regions_build_manifest.json`、`stable_regions_software_inputs.json`。

软件结果：两配色各五个完整显示帧，共 7987200 个源图 RGB/掩码检查；每组在真实检测结果链中切换四页面、三倍率和参数版本，包含移动及第七采集帧缺色。独立页面检查另覆盖 28 组、32 个完整显示帧、25559040 个图像区像素。
'''
text=re.sub(r'<!-- FINAL_BUILD_BEGIN -->.*?<!-- FINAL_BUILD_END -->','<!-- FINAL_BUILD_BEGIN -->\n'+block+'<!-- FINAL_BUILD_END -->',text,flags=re.S)
report.write_text(text,encoding='utf-8')
readme=R/'README.md';text=readme.read_text(encoding='utf-8')
needle='[上板与校准](docs/双色工具正式功能版上板.md)'
text=text.replace(needle,f'[正式 bit]({bit.relative_to(R).as_posix()})、[同源源码包]({(dest/"color_regions_stable_source.zip").relative_to(R).as_posix()})。\n\n'+needle,1)
readme.write_text(text,encoding='utf-8')
paths={R/n for n in json.loads((attempt/'inputs.json').read_text(encoding='utf-8'))}
paths|={p for folder in ('rtl','scripts','sim') for p in (R/folder).rglob('*') if p.is_file() and p.suffix.lower() in ('.v','.sv','.py','.txt','.json','.mem','.hex')}
paths|={R/'README.md',R/'docs/双色工具正式功能版上板.md',R/'docs/复杂环境色环检测_问题总结与改进建议.md',R/'docs/color_regions_implementation_status.md',report}
paths|={p for p in (R/'reports').glob('stable_*') if p.is_file() and p.name!='stable_regions_delivery.json'}
paths|={R/'scripts/build_target_color_regions.tcl',R/'scripts/generate_color_regions.py',R/'scripts/generate_target.py',R/'scripts/audit_color_regions.py'}
manifest={q.relative_to(R).as_posix():sha(q) for q in sorted(paths)}
archive=dest/'color_regions_stable_source.zip'
with zipfile.ZipFile(archive,'x',zipfile.ZIP_DEFLATED) as z:
    for q in sorted(paths):z.write(q,q.relative_to(R))
    z.writestr('SOURCE_MANIFEST.json',json.dumps(manifest,ensure_ascii=False,indent=2))
with zipfile.ZipFile(archive) as z:
    assert set(z.namelist())==set(manifest)|{'SOURCE_MANIFEST.json'}
    for n,h in manifest.items():assert hashlib.sha256(z.read(n)).hexdigest()==h,n
outputs={q.relative_to(R).as_posix():sha(q) for q in sorted(dest.iterdir()) if q.is_file()}
delivery={**obj,'bit':bit.relative_to(R).as_posix(),'source_zip':archive.relative_to(R).as_posix(),
    'source_zip_sha256':sha(archive),'outputs':outputs,'source_files':manifest,
    'guide':'docs/双色工具正式功能版上板.md','validation':'reports/双色工具正式功能版验证报告.md',
    'hardware_records':['reports/stable_regions_hardware_trials.csv','reports/stable_regions_hardware_metrics.csv'],
    'hardware_acceptance':'PENDING; no board download/Flash write in this task',
    'git_action':'Working changes on docs/color-regions-env-issues; no commit or push performed'}
write_new(R/'reports/stable_regions_delivery.json',delivery)
write_new(dest/'delivery.json',delivery)
shutil.copy2(report,dest/'验证报告.md');shutil.copy2(R/'docs/双色工具正式功能版上板.md',dest/'上板操作.md')
print('STABLE_PRODUCTION_DELIVERY_PASS',dest,sha(bit),'source_files',len(manifest),flush=True)
