"""Exact source/branch/project guards for the independent native candidate."""
from pathlib import Path
import hashlib,json,re,subprocess
from stage1_policy import check_protected as legacy_protected
from stage1_project import check_project
R=Path(__file__).resolve().parents[1]
BASE='4081ad0a067c7f1cca31fed15fc1bed8b210d704'
sha=lambda p:hashlib.sha256(Path(p).read_bytes()).hexdigest()
def git(root,*args):
    return subprocess.check_output(['git','-c','safe.directory='+Path(root).as_posix(),*args],cwd=root,text=True).strip()
def check_branch(root):
    branch=git(root,'branch','--show-current');assert branch=='Final_Mode_1028',branch
    subprocess.run(['git','-c','safe.directory='+Path(root).as_posix(),'merge-base','--is-ancestor',BASE,'HEAD'],cwd=root,check=True)
    return branch
def check_protected():
    legacy_protected()
    old=R/'build/target_region_sequence_stage1_20261028_170103'
    protected={old/'target_color_regions.bit':'016b6a0c3eca8bbddfe705d8b57210f03a7a5948173e0c748c83e96dac127956',
      old/'region_sequence_same_source.zip':'655852c0ee25d62340cfc1b978aec392f950283ad48e0924a34c9eeef4330ed1',
      R/'td_project/target_color_regions_stage1.al':'6b9d309fdd45fedead3a1419d7ed0862d385f34d286f6bf74df517f3cbe55ad0'}
    for p,h in protected.items():assert sha(p)==h,'Protected candidate/user project changed '+str(p)
    assert sha(old/'inputs.json')=='9f6cd8454409df7e5eea6b756be989105e93980903d12cd2ea9ad277dc0392f4'
    previous=json.loads((old/'inputs.json').read_text(encoding='utf-8'))
    for n,h in previous.items():assert sha(R/n)==h,'Original approved compiler input changed '+n
    return len(previous)
def compiler_paths(root=R):
    project=root/'td_project/target_color_regions_native_zoom.al'
    paths={project,root/'td_project/stage1_pins.adc',root/'td_project/native_zoom.sdc',
           root/'rtl/03_tool_detection/target_config.json',root/'rtl/color_regions/native_zoom_config.json',
           root/'vendor_reference/sc500cs_native_2592.json'}
    for n in re.findall(r'<File Path="([^"]+)"',project.read_text(encoding='utf-8')):
        p=(project.parent/n).resolve();assert p.is_relative_to(root),p
        if p.is_file():paths.add(p)
    paths.update(p for p in (root/'user_source').rglob('*') if p.is_file() and 'log' not in p.parts)
    paths.update(p for p in (root/'ip/refined_ddr2').rglob('*') if p.is_file())
    return paths
def canonical_build_inputs(inputs):
    check_branch(R);check_protected()
    assert set(inputs)=={p.relative_to(R).as_posix() for p in compiler_paths()},'Native compiler set differs'
    assert all(sha(R/n)==h for n,h in inputs.items()),'Native compiler input changed'
    from native_zoom_codegen import assets
    expected=assets()
    for n,s in expected.items():
        p=R/n
        if n.endswith('.al'):check_project(p,s)
        else:assert p.read_bytes()==s.encode('utf-8'),'Native generated bytes differ '+n
    assert (R/'td_project/native_zoom.sdc').read_bytes()==expected['td_project/native_zoom.sdc'].encode('utf-8')
    return len(inputs)
