"""Generate calibrated capture wrapper and OSD from ONE editable JSON config.
No network, image regeneration, or edits to ScalingTest assets are performed.
"""
from pathlib import Path
import json,hashlib,re
from PIL import Image,ImageFont,ImageDraw
ROOT=Path(__file__).resolve().parents[1]
cfg=json.loads((ROOT/'rtl/03_tool_detection/target_config.json').read_text())
assert all(isinstance(v,int) for v in cfg.values())
assert 1<=cfg['L_mm']<=9999 and 0<=cfg['D_mm']<=9999
assert 0<=cfg['color_min']<=255 and 0<=cfg['color_diff']<=255
assert 1<=cfg['ratio_den']<=16 and 1<=cfg['ratio_num']<=16
assert 1<=cfg['area_min']<=cfg['area_max']<=921600
assert 0<=cfg['fill_percent_min']<=100 # 0: report fill, do not reject sparse colors
assert 1<=cfg['separation_min_px']<cfg['separation_max_px']<=1468
assert 0<=cfg['yp_min']<=255 and 0<=cfg['yp_diff']<=255
assert 1<=cfg['yp_ratio_num']<=16 and 1<=cfg['yp_ratio_den']<=16 and 1<=cfg['yp_balance']<=16
assert 1<=cfg['long_press_ms']<=60000
assert 1<=cfg['confirm_frames']<=255 and 1<=cfg['max_step_px']<=1279
def write(rel,text):
    p=ROOT/rel;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(text,encoding='utf-8',newline='\n')
params=','.join(f'.{name}({cfg[key]})' for name,key in [('COLOR_MIN','color_min'),('COLOR_DIFF','color_diff'),('RATIO_NUM','ratio_num'),('RATIO_DEN','ratio_den'),('AREA_MIN','area_min'),('AREA_MAX','area_max'),('FILL_PERCENT_MIN','fill_percent_min'),('YP_MIN','yp_min'),('YP_DIFF','yp_diff'),('YP_RATIO_NUM','yp_ratio_num'),('YP_RATIO_DEN','yp_ratio_den'),('YP_BALANCE','yp_balance')])
tparams=','.join(f'.{name}({cfg[key]})' for name,key in [('L_MM','L_mm'),('D_MM','D_mm'),('SEP_MIN','separation_min_px'),('SEP_MAX','separation_max_px'),('MAX_STEP','max_step_px'),('CONFIRM_FRAMES','confirm_frames')])
write('rtl/04_tracking/target_capture_pipeline.v',f'''// Generated by scripts/generate_target.py. Edit target_config.json instead.
`default_nettype none
module target_capture_pipeline(
 input wire I_clk,I_rst_n,I_sof,I_valid,I_fault,
 input wire [95:0] I_rgb,input wire I_pair,input wire I_enable,input wire [7:0] I_session,
 output wire [31:0] O_frame_id,output wire O_valid,output wire [255:0] O_meta
);
 wire dv;wire [255:0] dm;
 target_detector #({params}) u_detect(
 .I_clk(I_clk),.I_rst_n(I_rst_n),.I_sof(I_sof),.I_valid(I_valid),.I_frame_fault(I_fault),
 .I_pair(I_pair),.I_enable(I_enable),.I_session(I_session),.I_rgb(I_rgb),.O_frame_id(O_frame_id),.O_valid(dv),.O_meta(dm));
 target_tracker #({tparams}) u_track(
 .I_clk(I_clk),.I_rst_n(I_rst_n),.I_enable(I_enable),.I_session(I_session),
 .I_pair(I_pair),.I_valid(dv),.I_meta(dm),.O_valid(O_valid),.O_meta(O_meta));
endmodule
`default_nettype wire
''')
states=['待命','搜索中','锁定跟踪','失锁','已停止','按键冲突','视频未就绪']
modes=['原图','边缘','灰度','二值化']
kq=(cfg['D_mm']*65536+cfg['L_mm']//2)//cfg['L_mm']
ktext=f'{kq/65536:.3f}'
row3=f"L={cfg['L_mm']:04d}mm D={cfg['D_mm']:04d}mm K={ktext}"
labels=['红色标记点A','蓝色标记点B','黄色标记点A','紫色标记点B','十字准心T','估算尖端']
diagnoses=[' ','帧无效','缺少双色','面积不符','填充不足','间距不符','尖端越界','位移或帧号异常','采集溢出','等待结果','确认中','已锁定']
color_states=['待结果','帧无效','无像素','面积不符','填充不足','候选']
static=diagnoses+color_states+['诊断：A像素： 填充：%缺少A缺少B']+labels+['配色：红蓝黄紫','标注：开关','模式：','倍率：','状态：','红A前 蓝B后 估算尖端：(','安路科技',row3,')0123456789,-T']
chars=''.join(sorted(set(' '.join(static+states+modes))))
assert len(chars)<=128
fontpath=Path('C:/Windows/Fonts/simhei.ttf');font=ImageFont.truetype(str(fontpath),24)
lab=(ROOT/'vendor_reference/lab3_osd/osd_char_lib.v').read_text(encoding='utf-8')
vendor={}
for key,body in re.findall(r'CHAR_(\w+):\s*begin(.*?)endcase',lab,re.S):
    c={'AN':'安','LU':'路','COLON':'：'}.get(key,key)
    if len(c)!=1:continue
    im=Image.new('L',(16,16))
    for row,bits in re.findall(r"4'd(\d+):\s*O_row_bits\s*=\s*16'h([0-9a-fA-F]+)",body):
        for x in range(16):im.putpixel((x,int(row)),255 if int(bits,16)&(1<<(15-x)) else 0)
    bb=im.getbbox()
    if bb:
        im=im.crop(bb);vendor[c]=im.resize((min(22,round(im.width*22/im.height)),22),Image.Resampling.NEAREST)
rows=[];atlas=Image.new('RGB',(384,((len(chars)+15)//16)*24),'#102030')
for idx,c in enumerate(chars):
    im=Image.new('L',(24,24))
    if c in vendor:im.paste(vendor[c],((24-vendor[c].width)//2,1))
    else:
        l,t,r,b=font.getbbox(c);ImageDraw.Draw(im).text(((24-r+l)//2-l,(24-b+t)//2-t),c,font=font,fill=255)
    im=im.point(lambda v:255 if v>=96 else 0)
    for y in range(24):rows.append(sum(1<<(23-x) for x in range(24) if im.getpixel((x,y))))
    atlas.paste(Image.new('RGB',(24,24),'white'),((idx%16)*24,(idx//16)*24),im)
atlaspath=ROOT/'reports/target_preview/glyphs.png';atlaspath.parent.mkdir(parents=True,exist_ok=True);atlas.save(atlaspath)
write('rtl/09_osd_ui/target_glyph_rom.v','\n'.join([
'module target_glyph_rom(input wire clk,input wire [11:0] addr,output reg [23:0] q);',
'(* ram_style="block" *) reg [23:0] mem[0:4095];','integer i;','initial begin',
'for(i=0;i<4096;i=i+1) mem[i]=0;',*[f"mem[{i}]=24'h{v:06x};" for i,v in enumerate(rows) if v],
'end','always @(posedge clk) q<=mem[addr];','endmodule','']))
gid=lambda c:chars.index(c)
def case_text(s,start=0):return '\n'.join(f'{i+start}:glyph=7\'d{gid(c)};' for i,c in enumerate(s))
def multi(texts,sel):
    return f'case({sel})\n'+'\n'.join(f'{i}:case(column)\n{case_text(s)}\nendcase' for i,s in enumerate(texts))+'\nendcase'
template=(ROOT/'scripts/target_osd_template.v.txt').read_text(encoding='utf-8')
replacements={'@AREA_MIN@':str(cfg['area_min']),'@AREA_MAX@':str(cfg['area_max']),
'@DIAG_ROW@':case_text('像素：',1)+'\n'+case_text('填充：',11)+'\n'+case_text('%',17),'@DIAG_TITLE@':case_text('诊断：'),
'@COLOR_STATUS@':multi(color_states,'color_status'),'@DIAG_REASONS@':multi(diagnoses,'diagnosis'),
'@MISSING_A@':case_text('缺少A'),'@MISSING_B@':case_text('缺少B'),'@MISSING_BOTH@':case_text('缺少双色'),
'@SPACE@':str(gid(' ')),'@ZERO@':str(gid('0')),'@DASH@':str(gid('-')),
'@A@':str(gid('A')),'@B@':str(gid('B')),'@T@':str(gid('T')),
'@ROW1@':case_text('模式：',0)+'\n'+case_text('倍率：',8)+'\n'+case_text('状态：',14),
'@MODES@':multi(modes,'I_mode'),'@STATES@':multi(states,'I_state'),
'@ROW2@':case_text('配色：',0)+'\n'+case_text('估算尖端：(',7)+'\n'+case_text(',',18)+'\n'+case_text(')',23),
'@PAIR_NAMES@':multi(['红蓝','黄紫'],'I_pair'),'@A_NAMES@':multi([labels[0],labels[2]],'I_pair'),'@B_NAMES@':multi([labels[1],labels[3]],'I_pair'),'@TIP_NAME@':case_text(labels[4]),'@TIP_NOTE@':case_text(labels[5]),'@SHOW_NAME@':multi(['关','开'],'I_show'),'@ROW3@':case_text(row3)+'\n'+case_text('标注：',27),'@BRAND@':case_text('安路科技')}
for a,b in replacements.items():template=template.replace(a,b)
assert '@' not in template.replace('always @','always ')
write('rtl/09_osd_ui/target_osd.v',template)
files=['rtl/04_tracking/target_capture_pipeline.v','rtl/09_osd_ui/target_glyph_rom.v','rtl/09_osd_ui/target_osd.v','rtl/03_tool_detection/target_config.json','scripts/target_osd_template.v.txt']
write('reports/target_generation_manifest.json',json.dumps({'config':cfg,'K_Q16':kq,'K_display':ktext,'characters':chars,'contest_glyphs_reused':''.join(c for c in chars if c in vendor),'font_sha256':hashlib.sha256(fontpath.read_bytes()).hexdigest(),'files':{p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in files}},ensure_ascii=False,indent=2)+'\n')
top=ROOT/'rtl/00_top_control/criticalwork_top.v'
top.write_text(re.sub(r'LONG_PRESS_MS\(\d+\)',f"LONG_PRESS_MS({cfg['long_press_ms']})",top.read_text(encoding='utf-8')),encoding='utf-8',newline='\n')
print(f'Generated target pipeline and {len(chars)} OSD glyphs; L={cfg["L_mm"]}, D={cfg["D_mm"]}, K={ktext}')
